    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        model = (DefaultTableModel) jTable1.getModel();
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow != -1) {
            try {
                Object firstname = model.getValueAt(selectedRow, 0);
                jTextField1.setText(firstname != null ? firstname.toString() : "");
                Object middlename = model.getValueAt(selectedRow, 1);
                jTextField2.setText(middlename != null ? middlename.toString() : "");
                Object lastname = model.getValueAt(selectedRow, 2);
                jTextField3.setText(lastname != null ? lastname.toString(): "");
                String gender = model.getValueAt(selectedRow, 4) != null ? model.getValueAt(selectedRow, 4).toString() : "";
                if (gender.equalsIgnoreCase("Male")) {
                    jRadioButton1.setSelected(true);
                }
                else if (gender.equalsIgnoreCase("Female")) {
                    jRadioButton2.setSelected(true);
                }
                String age = model.getValueAt(selectedRow, 3) != null ? model.getValueAt(selectedRow, 3).toString() : "";
                jComboBox1.setSelectedItem(age);
                String language = model.getValueAt(selectedRow, 5) != null ? model.getValueAt(selectedRow, 5).toString() : "";
                jCheckBox1.setSelected(language.contains("English"));
                jCheckBox2.setSelected(language.contains("Bisaya"));
                jCheckBox3.setSelected(language.contains("Tagalog"));
                String datedate = model.getValueAt(selectedRow, 6) != null ? model.getValueAt(selectedRow, 6).toString() : "";
                Date deyt = new SimpleDateFormat("MM/dd/yyyy").parse(datedate);
                jDateChooser1.setDate(deyt);
                
            }
            catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Error loading info.", "Updating info error", JOptionPane.ERROR_MESSAGE);
            }
        }
        else {
            JOptionPane.showMessageDialog(this, "Select a row first.");
        }
    }//GEN-LAST:event_jTable1MouseClicked

