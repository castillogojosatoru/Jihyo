    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        try {
            String radioB = "";
            String language;
            String date = "";
            StringBuilder sb = new StringBuilder();
            JCheckBox[] check = {jCheckBox1, jCheckBox2, jCheckBox3};
        
            for (JCheckBox jcheckbox : check) {
                if (jcheckbox.isSelected()) {
                    sb.append(jcheckbox.getText()).append("\n");
                }
            }
        
            model = (DefaultTableModel) jTable1.getModel();
            jTable1.setModel(model);
            Date selectedDate = jDateChooser1.getDate();
            SimpleDateFormat sdf = new SimpleDateFormat("MM/dd/yyyy");
            String formattedDate = sdf.format(selectedDate);
            date = formattedDate;
            if (selectedDate.equals(null)) {
                JOptionPane.showMessageDialog(this, "Please input birthdate.");
                return;
            }
        
            if (jRadioButton1.isSelected()) {
                radioB = "Male";
            }
            else if (jRadioButton2.isSelected()) {
                radioB = "Female";
            }
        
            language = sb.toString();
        
            Object[] rowData = new Object[] {jTextField1.getText(), jTextField2.getText(), jTextField3.getText(), jComboBox1.getSelectedItem(), radioB, language, date};
        
            if (editingRow >= 0) {
            
                model.setValueAt(jTextField1.getText(), editingRow, 0);
                model.setValueAt(jTextField2.getText(), editingRow, 1);
                model.setValueAt(jTextField3.getText(), editingRow, 2);
                model.setValueAt(jComboBox1.getSelectedItem(), editingRow, 3);
                model.setValueAt(radioB, editingRow, 4);
                model.setValueAt(language, editingRow, 5);
                model.setValueAt(date, editingRow, 6);
                editingRow = -1;
            }
            else {
                model.addRow(new Object[] {jTextField1.getText(), jTextField2.getText(), jTextField3.getText(), jComboBox1.getSelectedItem(), radioB, language, date});
            }
            clearFormFields();
            JOptionPane.showMessageDialog(this, "Info added successfully.", "Info added", JOptionPane.INFORMATION_MESSAGE);
        } 
        catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Please fill up the fields.", "Fill up error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_saveButtonActionPerformed

    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        model = (DefaultTableModel) jTable1.getModel();
        
        if (jTable1.getSelectedRowCount() == 1) {

              int con = JOptionPane.showConfirmDialog(this, "Do you want to delete this?");
              if (con == 0) {
                  model.removeRow(jTable1.getSelectedRow());
                  JOptionPane.showMessageDialog(this, "Info deleted.");
              }
              else if (con == 1) {
                  JOptionPane.showMessageDialog(this, "Okay.");
              }
        }
        else {
            if (jTable1.getSelectedRowCount() == 0) {
                JOptionPane.showMessageDialog(this, "Info is empty.", "Emtpy", JOptionPane.ERROR_MESSAGE);
            }
            else {
                JOptionPane.showMessageDialog(this, "Please select a data to delete.", "No data selection", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_deleteButtonActionPerformed

