    private void saveUpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveUpdateButtonActionPerformed
        if (editingRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a student info from the table to update.", "Unknown Info Update", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            String radioButton = "";
        
            if (maleRButton.isSelected()) {
                radioButton = "Male";
            }
            else if (femaleRButton.isSelected()) {
                radioButton = "Female";
            }
            else {
                JOptionPane.showMessageDialog(this, "Please input your gender.", "Input Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        
//            Object[] rowDate = new Object[] {fullNameTextField.getText(), radioButton, programComboBox.getSelectedItem()};
        
            JOptionPane.showMessageDialog(this, "Student info updated successfully.", "Info updated", JOptionPane.INFORMATION_MESSAGE);
            
            if (editingRow >= 0) {
                model.setValueAt(fullNameTextField.getText(), editingRow, 0);
                model2.setValueAt(fullNameTextField.getText(), editingRow, 0);
                model.setValueAt(radioButton, editingRow, 1);
                model2.setValueAt(radioButton, editingRow, 1);
                model.setValueAt(programComboBox.getSelectedItem(), editingRow, 2);
                model2.setValueAt(programComboBox.getSelectedItem(), editingRow, 2);
                editingRow = -1;
            }
            else {
                JOptionPane.showMessageDialog(this, "Please select a row to update.");
            }
            clearFields();
            if (fullNameTextField.getText().isEmpty()) {
                saveUpdateButton.setEnabled(false);
            }
            else {
                saveUpdateButton.setEnabled(true);
            }
        } 
        catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Unknown error has been occured.", "Unknown Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_saveUpdateButtonActionPerformed

