    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked

        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow != -1) {
            try {
                editingRow = selectedRow;
                Object fullName = model.getValueAt(selectedRow, 0);
                fullNameTextField.setText(fullName != null ? fullName.toString() : "");
                String gender = model.getValueAt(selectedRow, 1) != null ? model.getValueAt(selectedRow, 1).toString() : "";
                if (gender.equalsIgnoreCase("Male")) {
                    maleRButton.setSelected(true);
                }
                else if (gender.equalsIgnoreCase("Female")) {
                    femaleRButton.setSelected(true);
                }
                String program = model.getValueAt(selectedRow, 2) != null ? model.getValueAt(selectedRow, 2).toString() : "";
                programComboBox.setSelectedItem(program);
                saveUpdateButton.setEnabled(true);
            } 
            catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Unknown error has been occured. Please try again.", "Unknown Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void fullNameTextFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_fullNameTextFieldKeyReleased
        
        if (fullNameTextField.getText().isBlank()) {
            saveUpdateButton.setEnabled(false);
        }
        else {
            saveUpdateButton.setEnabled(true);
        }
    }//GEN-LAST:event_fullNameTextFieldKeyReleased

